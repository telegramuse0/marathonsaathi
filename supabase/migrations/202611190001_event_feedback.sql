create table if not exists public.event_feedback (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.marathons(id) on delete cascade,
  runner_name text not null check (char_length(trim(runner_name)) between 2 and 60),
  runner_email text not null check (char_length(trim(runner_email)) <= 254),
  registration_reference text not null check (char_length(trim(registration_reference)) between 3 and 80),
  route_rating smallint not null check (route_rating between 1 and 5),
  organization_rating smallint not null check (organization_rating between 1 and 5),
  water_rating smallint not null check (water_rating between 1 and 5),
  overall_rating smallint not null check (overall_rating between 1 and 5),
  comment text check (char_length(coalesce(comment, '')) <= 1000),
  is_verified boolean not null default false,
  created_at timestamptz not null default now(),
  constraint event_feedback_unique_runner unique (event_id, runner_email)
);

create index if not exists event_feedback_public_idx
  on public.event_feedback (event_id, is_verified, created_at desc);

alter table public.event_feedback enable row level security;

grant select, insert on public.event_feedback to anon, authenticated;
grant update, delete on public.event_feedback to authenticated;
grant usage, select on sequence public.event_feedback_id_seq to anon, authenticated;

create policy "Public can submit unverified race feedback"
  on public.event_feedback for insert to anon, authenticated
  with check (is_verified = false);

create policy "Public can read verified race feedback"
  on public.event_feedback for select to anon, authenticated
  using (is_verified = true);

create policy "Admins can manage all race feedback"
  on public.event_feedback for all to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
