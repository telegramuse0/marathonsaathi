begin;

alter table public.marathons
  add column if not exists is_featured boolean not null default false,
  add column if not exists registration_closes date;

-- Reviews are public immediately. Keep only fields that are safe to show publicly.
alter table public.event_feedback
  alter column runner_email drop not null,
  alter column registration_reference drop not null;

update public.event_feedback set is_verified = true where is_verified = false;
alter table public.event_feedback alter column is_verified set default true;

-- Public reviews never expose the private contact and bib fields.
revoke select on public.event_feedback from anon, authenticated;
grant select (id, event_id, runner_name, route_rating, organization_rating, water_rating, overall_rating, comment, is_verified, created_at)
  on public.event_feedback to anon, authenticated;

drop policy if exists "Public can submit unverified race feedback" on public.event_feedback;
drop policy if exists "Public can read verified race feedback" on public.event_feedback;
drop policy if exists "Public can read race feedback" on public.event_feedback;

create policy "Public can submit race reviews"
  on public.event_feedback for insert to anon, authenticated
  with check (is_verified = true);

create policy "Public can read race reviews"
  on public.event_feedback for select to anon, authenticated
  using (is_verified = true);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 2 and 80),
  email text not null check (char_length(trim(email)) between 5 and 254),
  message text not null check (char_length(trim(message)) between 10 and 3000),
  created_at timestamptz not null default now()
);

alter table public.contact_messages enable row level security;
grant insert on public.contact_messages to anon, authenticated;
grant select, delete on public.contact_messages to authenticated;
grant usage, select on sequence public.contact_messages_id_seq to anon, authenticated;

create policy "Public can send contact messages"
  on public.contact_messages for insert to anon, authenticated
  with check (
    char_length(trim(name)) between 2 and 80
    and char_length(trim(email)) between 5 and 254
    and char_length(trim(message)) between 10 and 3000
  );

create policy "Admins can read contact messages"
  on public.contact_messages for select to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()));

create policy "Admins can delete contact messages"
  on public.contact_messages for delete to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()));

commit;
