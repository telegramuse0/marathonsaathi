begin;

create table if not exists public.event_feedback_replies (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.event_feedback(id) on delete cascade,
  author_name text not null check (char_length(trim(author_name)) between 2 and 60),
  message text not null check (char_length(trim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists event_feedback_replies_review_created_idx
  on public.event_feedback_replies (review_id, created_at);

alter table public.event_feedback_replies enable row level security;

grant select, insert on public.event_feedback_replies to anon, authenticated;
grant delete on public.event_feedback_replies to authenticated;
grant usage, select on sequence public.event_feedback_replies_id_seq to anon, authenticated;

drop policy if exists "Anyone can read review replies" on public.event_feedback_replies;
create policy "Anyone can read review replies"
  on public.event_feedback_replies for select to anon, authenticated
  using (true);

drop policy if exists "Anyone can reply to reviews" on public.event_feedback_replies;
create policy "Anyone can reply to reviews"
  on public.event_feedback_replies for insert to anon, authenticated
  with check (
    char_length(trim(author_name)) between 2 and 60
    and char_length(trim(message)) between 1 and 1000
    and exists (select 1 from public.event_feedback f where f.id = review_id and f.is_verified = true)
  );

drop policy if exists "Admins can delete review replies" on public.event_feedback_replies;
create policy "Admins can delete review replies"
  on public.event_feedback_replies for delete to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()));

commit;

